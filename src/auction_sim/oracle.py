"""Exact exhaustive hindsight benchmark for tiny workloads."""

from __future__ import annotations

from dataclasses import dataclass
from itertools import combinations, permutations
import math
from typing import Sequence

from .engine import Simulator
from .models import Admission, Decision, FreeCapacity, Job, Order, ServerConfig, UsageInterval


@dataclass(frozen=True)
class OracleResult:
    welfare: float
    exact: bool
    upper_bound: float
    algorithm: str
    nodes: int


class OracleSearchLimit(RuntimeError):
    """Raised instead of returning an uncertified result after a bounded search."""

    def __init__(self, message: str, *, upper_bound: float, nodes: int):
        super().__init__(message)
        self.upper_bound = upper_bound
        self.nodes = nodes


@dataclass(frozen=True)
class _Action:
    ids: tuple[str, ...]


class _NeedChoice(Exception):
    def __init__(self, pending: Sequence[Order], free: FreeCapacity, t: float):
        self.pending, self.free, self.t = tuple(pending), free, t


class _ReplayPolicy:
    def __init__(self, actions: tuple[_Action, ...], decision_times_s: tuple[float, ...]):
        self.actions = actions
        self.index = 0
        self.decision_times_s = decision_times_s

    def step(self, pending, free_capacity, t):
        # Forced empty decisions do not branch or consume a replay action. This
        # also keeps long outputs from creating one search level per token.
        if not any(order.reserved_kv_tokens <= free_capacity.kv_tokens for order in pending) or free_capacity.batch_slots < 1:
            return Decision()
        if self.index >= len(self.actions):
            raise _NeedChoice(pending, free_capacity, t)
        action = self.actions[self.index]
        self.index += 1
        available = {order.request_id: order for order in pending}
        if any(rid not in available for rid in action.ids):
            raise RuntimeError("oracle replay diverged from its decision path")
        return Decision(tuple(Admission(rid, available[rid].bid_per_token) for rid in action.ids))

    def observe(self, interval: UsageInterval) -> None:
        pass

    def next_wakeup(self, t: float):
        return next((when for when in self.decision_times_s if when > t), None)


def exact_hindsight_oracle(
    jobs: Sequence[Job], server: ServerConfig, arrival_horizon_s: float,
    *, max_jobs: int = 6, max_nodes: int = 250_000,
    decision_times_s: Sequence[float] = (),
) -> OracleResult:
    """Exhaustively maximize served value over all admission choices.

    The oracle makes a choice at every decision opportunity generated by the same
    event engine (arrival, release, or pending-order deadline), plus any supplied
    ``decision_times_s``. It can admit any feasible ordered subset of the current
    pending orders. Prices do not affect service feasibility, so admitted requests
    are assigned their bids.
    """
    jobs = tuple(jobs)
    for name, value in (("max_jobs", max_jobs), ("max_nodes", max_nodes)):
        if isinstance(value, bool) or not isinstance(value, int) or value < 1:
            raise ValueError(f"{name} must be a positive integer")
    raw_calendar = tuple(decision_times_s)
    if any(isinstance(t, bool) or not isinstance(t, (int, float)) or not math.isfinite(t) or t < 0 for t in raw_calendar):
        raise ValueError("decision_times_s must contain finite nonnegative times")
    calendar = tuple(sorted(set(raw_calendar)))
    offered_bound = sum(job.total_value for job in jobs)
    if len(jobs) > max_jobs:
        raise OracleSearchLimit(
            f"exact oracle is limited to {max_jobs} jobs (received {len(jobs)})",
            upper_bound=offered_bound, nodes=0,
        )
    if max_nodes < 1:
        raise ValueError("max_nodes must be positive")
    best = 0.0
    nodes = 0

    # Iterative depth-first search avoids recursion limits on long token traces.
    frontier: list[tuple[_Action, ...]] = [()]
    while frontier:
        actions = frontier.pop()
        nodes += 1
        if nodes > max_nodes:
            raise OracleSearchLimit(
                f"oracle search exceeded max_nodes={max_nodes}",
                upper_bound=offered_bound, nodes=nodes - 1,
            )
        policy = _ReplayPolicy(actions, calendar)
        try:
            result = Simulator(server).run(jobs, policy, arrival_horizon_s)
        except _NeedChoice as choice:
            orders = tuple(choice.pending)
            candidates: list[tuple[str, ...]] = [()]
            # Admission order determines FIFO prefill order, so enumerate permutations.
            for count in range(1, len(orders) + 1):
                for group in combinations(orders, count):
                    if count > choice.free.batch_slots:
                        continue
                    if sum(o.reserved_kv_tokens for o in group) > choice.free.kv_tokens:
                        continue
                    for ordering in permutations(group):
                        candidates.append(tuple(o.request_id for o in ordering))
            frontier.extend(actions + (_Action(ids),) for ids in reversed(candidates))
            continue
        welfare = sum(item.job.total_value for item in result.requests if item.status == "completed")
        if welfare > best:
            best = welfare

    return OracleResult(
        welfare=best, exact=True, upper_bound=offered_bound,
        algorithm=("exhaustive event-decision ordered-subset search" +
                   (" with supplied action calendar" if calendar else "")),
        nodes=nodes,
    )
